function applyEnglishData() {
  CATEGORIES.forEach((c) => { if (EN_CATEGORIES[c.id]) c.name = EN_CATEGORIES[c.id]; });
  for (const [k, [name, how, note]] of Object.entries(EN_ALLERGENS)) {
    if (!ALLERGENS[k]) continue;
    Object.assign(ALLERGENS[k], { name, how, note });
  }
  FOODS.forEach((f) => {
    const e = EN_FOODS[f.id];
    if (!e) return;
    f.name = e[0];
    if (e[1] !== undefined) f.tip = e[1];
    if (f.choke) f.choke = e[2] || f.choke;
  });
  GUIDE.forEach((g, i) => { if (EN_GUIDE[i]) { g.title = EN_GUIDE[i][0]; g.body = EN_GUIDE[i][1]; } });
  SOURCES.forEach((s, i) => { if (EN_SOURCES[i]) s.name = EN_SOURCES[i]; });
}
